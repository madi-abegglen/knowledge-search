"""Split requirements.txt into runtime and audit-tooling lockfiles with ZERO version changes.

Run from the repo root:  .\\.venv\\Scripts\\python.exe scripts\\split_lockfile.py [--write]

Moves the exact existing lines of the 16 audit-tooling packages (pip-audit and its dependency
tree) from requirements.txt to requirements-dev.txt, preserving each line's bytes (including
line endings). Without --write it only prints the proof. Always verifies:
- every original line appears exactly once across the two outputs, byte for byte;
- no line was changed, added or dropped; relative order is preserved;
- per-package pins are identical to the original.
"""

from collections import Counter
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "requirements.txt"
DEV_LOCK = ROOT / "requirements-dev.txt"

# pip-audit (requirements-dev.in) and its transitive dependencies that the runtime does not need.
# Determined by resolving requirements.in alone in a clean venv: these 16 were the only packages
# of the current lock that it did not install.
DEV_PACKAGES = {
    "boolean-py", "cachecontrol", "cyclonedx-python-lib", "defusedxml", "license-expression",
    "msgpack", "packageurl-python", "pip-api", "pip-audit", "pip-requirements-parser",
    "platformdirs", "py-serializable", "pyparsing", "sortedcontainers", "tomli", "tomli-w",
}
HEADER = (b"# Audit/dev tooling lock (pip-audit and its dependencies). Not needed to run the app.\r\n"
          b"# Generated by moving lines out of requirements.txt unchanged; edit requirements-dev.in instead.\r\n")


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def main(write: bool) -> int:
    original = LOCK.read_bytes()
    lines = original.splitlines(keepends=True)
    runtime_lines, dev_lines = [], []
    for line in lines:
        name = line.decode("utf-8").split("==", 1)[0].strip()
        (dev_lines if norm(name) in DEV_PACKAGES else runtime_lines).append(line)

    found = {norm(l.decode().split("==", 1)[0].strip()) for l in dev_lines}
    assert found == DEV_PACKAGES, f"missing from lock: {DEV_PACKAGES - found}"

    # proof: only moves
    assert Counter(runtime_lines) + Counter(dev_lines) == Counter(lines), "lines were changed or lost"
    assert runtime_lines + dev_lines != lines or not dev_lines
    assert [l for l in lines if l in set(runtime_lines)] == runtime_lines     # order preserved
    assert [l for l in lines if l in set(dev_lines)] == dev_lines
    old_pins = {norm(l.decode().split("==")[0].strip()): l.decode().strip().split("==")[1] for l in lines}
    new_pins = {norm(l.decode().split("==")[0].strip()): l.decode().strip().split("==")[1]
                for l in runtime_lines + dev_lines}
    assert old_pins == new_pins, "a pin changed"

    print(f"original lines: {len(lines)}")
    print(f"requirements.txt (runtime): {len(runtime_lines)} lines, all unchanged")
    print(f"requirements-dev.txt: {len(dev_lines)} lines moved unchanged (+2 comment header lines)")
    print("moved:", ", ".join(l.decode().strip() for l in dev_lines))
    print("version changes: 0   lines added: 0 (excluding the dev header)   lines changed: 0")

    if write:
        LOCK.write_bytes(b"".join(runtime_lines))
        DEV_LOCK.write_bytes(HEADER + b"".join(dev_lines))
        print("WRITTEN: requirements.txt and requirements-dev.txt")
    else:
        print("(dry run; pass --write to write the files)")
    return 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
